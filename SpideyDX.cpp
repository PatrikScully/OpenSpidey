i32 WinYield(void)
{
#if defined(_WIN32) && !defined(SPIDEY_STANDALONE)
	MSG msg;
	while (PeekMessageA(&msg, gHwnd, 0, 0, 0))
	{
		i32 bRet = GetMessageA(&msg, gHwnd, 0, 0);
		if (!bRet || bRet == -1)
		{
			return -1;
		}

		if (msg.message != 260 && msg.message != 261)
		{
			TranslateMessage(&msg);
			DispatchMessageA(&msg);
		}
	}
#elif defined(SPIDEY_STANDALONE)
	if (!Plat_Yield())
	{
		// window closed: same exit path as WM_CLOSE -> PostQuitMessage
		SPIDEYDX_Shutdown();
		exit(0);
	}
#endif

	return 117;
}

